const HTML_ENTITIES: Readonly<Record<string, string>> = {
  '&amp;': '&',
  '&lt;': '<',
  '&gt;': '>',
  '&quot;': '"',
  '&#39;': "'",
}

function decodeHtmlEntities(value: string) {
  return value.replace(/&(amp|lt|gt|quot|#39);/g, (entity) => HTML_ENTITIES[entity] || entity)
}

export function localizeComponentName(name: string) {
  const exact = COMPONENT_NAME_TRANSLATIONS[name]
  if (exact) return exact

  return name
    .replace(/^History (\d+):\s*/, '历史记录 $1：')
    .replace(/\s+\(enter\)$/, '（进入）')
    .replace(/\s+\(exit\)$/, '（退出）')
    .replace(/^P(\d+)\s+(.+)$/, 'Phi 第 $1 首：$2')
    .replace(/^#(\d+)\s+(.+)$/, '第 $1 名：$2')
    .replace(/^(.+)\s+(EZ|HD|IN|AT)$/, '$1（$2 谱面）')
    .replace(/^Calendar day (\d+)$/, '日历日期 $1')
    .replace(/^Challenge song (\d+)$/, '课题曲目 $1')
    .replace(/^Task song (\d+)$/, '任务曲目 $1')
    .replace(/\s+command group$/, '命令分组')
    .replace(/\s+heading$/, '标题')
    .replace(/\s+history card$/, ' 历史卡片')
    .replace(/\s+task card$/, ' 任务卡片')
    .replace(/\s+artwork$/, ' 曲绘')
    .replace(/^(\d+(?:\.\d+)?) label$/, '$1 标签')
    .replace(/^(\d+(?:\.\d+)?) songs$/, '$1 曲目')
}

export function localizeMarkupComponentNames(markup: string) {
  return markup.replace(/data-gjs-name="([^"]*)"/g, (_attribute, rawName: string) => (
    `data-gjs-name="${localizeComponentName(rawName)}"`
  ))
}

function markupNameForSelector(markup: string, selector: string) {
  const tags = markup.matchAll(/<[A-Za-z][^>]*\bdata-phi-selector="([^"]+)"[^>]*>/g)
  for (const match of tags) {
    if (decodeHtmlEntities(match[1]) !== selector) continue
    const name = match[0].match(/\bdata-gjs-name="([^"]+)"/i)?.[1]
    if (name) return localizeComponentName(decodeHtmlEntities(name))
  }
  return ''
}

export function componentLabelForSelector(selector: string, markup = '', groupLabel = '页面'): string {
  const exact = SELECTOR_LABELS[selector]
  if (exact) return exact

  const markupName = markupNameForSelector(markup, selector)
  if (markupName) return markupName

  const descendant = selector.match(/^(.*)\s+(p|span|img|svg|path)$/)
  if (descendant) {
    const parent = componentLabelForSelector(descendant[1], markup, groupLabel)
    const suffix = descendant[2] === 'img'
      ? '图片'
      : descendant[2] === 'svg'
        ? '图标'
        : descendant[2] === 'path'
          ? '路径'
          : descendant[2] === 'span'
            ? '强调文字'
            : '文字'
    return `${parent}${suffix}`
  }

  return `${groupLabel}元素`
}
